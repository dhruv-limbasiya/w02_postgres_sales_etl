Query 4: Monthly Revenue Trend  

SELECT dd.order_year,
    dd.order_month,
    SUM(f.sales) AS monthly_revenue
FROM dim_date dd
JOIN fact_sales f
ON dd.order_date = f.order_date
GROUP BY
	dd.order_year,
    dd.order_month
ORDER BY
    dd.order_year,
    dd.order_month;

